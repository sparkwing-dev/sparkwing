// Command apispec generates the controller policy inventory and shared JSON shapes.
package main

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"reflect"
	"regexp"
	"strings"

	"go.yaml.in/yaml/v3"

	"github.com/sparkwing-dev/sparkwing/internal/apierr"
	"github.com/sparkwing-dev/sparkwing/internal/capability"
)

func main() {
	if len(os.Args) != 1 {
		fmt.Fprintln(os.Stderr, "usage: apispec")
		os.Exit(2)
	}
	if err := writeSpec(os.Stdout, capability.Routes, wireOperations()); err != nil {
		fmt.Fprintln(os.Stderr, "apispec:", err)
		os.Exit(1)
	}
}

var pathParameter = regexp.MustCompile(`\{([^{}]+)\}`)

func writeSpec(out io.Writer, routes []capability.RoutePolicy, bodies map[string]wireOperation) error {
	builder := schemaBuilder{definitions: schema{}}
	paths, err := buildPaths(&builder, routes, bodies)
	if err != nil {
		return err
	}
	if builder.err != nil {
		return builder.err
	}
	doc := schema{
		"openapi":                 "3.1.0",
		"info":                    schema{"title": "Sparkwing controller API", "version": "1", "description": "The shared policy defines HTTP and local API socket authorization. x-sparkwing-policy preserves each complete access alternative; every grant within one alternative is required. Bindings, liveness and external proofs remain mandatory. JSON schemas describe serialization shapes, while the shared validators enforce semantic constraints. Unmapped success bodies are marked explicitly. Native runtime conformance requires separate acceptance evidence."},
		"paths":                   paths,
		"components":              schema{"schemas": builder.definitions},
		"x-sparkwing-error-codes": errorDefinitions(),
	}
	var buffer bytes.Buffer
	buffer.WriteString("# Generated by internal/apispec from capability.Routes and shared wire types.\n# Regenerate with bash bin/gen-api-docs.sh.\n")
	encoder := yaml.NewEncoder(&buffer)
	encoder.SetIndent(2)
	if err := encoder.Encode(doc); err != nil {
		return err
	}
	if err := encoder.Close(); err != nil {
		return err
	}
	n, err := out.Write(buffer.Bytes())
	if err == nil && n != buffer.Len() {
		return io.ErrShortWrite
	}
	return err
}

func jsonContent(value schema) schema {
	return schema{"application/json": schema{"schema": value}}
}

func buildPaths(builder *schemaBuilder, routes []capability.RoutePolicy, bodies map[string]wireOperation) (schema, error) {
	paths := schema{}
	seen := map[string]bool{}
	for _, route := range routes {
		key := route.Method + " " + route.Path
		if seen[key] || route.Method == "" || !strings.HasPrefix(route.Path, "/") {
			return nil, fmt.Errorf("invalid or duplicate policy route %q", key)
		}
		seen[key] = true
		path := strings.ReplaceAll(route.Path, "...}", "}")
		item, exists := paths[path].(schema)
		if !exists {
			item = schema{}
			paths[path] = item
		}
		method := strings.ToLower(route.Method)
		switch method {
		case "get", "post", "put", "delete", "patch", "head", "options", "trace":
		default:
			return nil, fmt.Errorf("invalid HTTP method %q", route.Method)
		}
		if item[method] != nil {
			return nil, fmt.Errorf("policy paths collide at %s %s", route.Method, path)
		}
		body, known := bodies[key]
		item[method] = operationDocument(builder, route, path, body, known)
	}
	for key := range bodies {
		if !seen[key] {
			return nil, fmt.Errorf("wire binding has no policy route: %s", key)
		}
	}
	return paths, nil
}

func operationDocument(builder *schemaBuilder, route capability.RoutePolicy, path string, body wireOperation, known bool) schema {
	op := schema{"x-sparkwing-policy": route, "summary": route.Method + " " + route.Path}
	params := []any{}
	for _, match := range pathParameter.FindAllStringSubmatch(path, -1) {
		params = append(params, schema{"name": match[1], "in": "path", "required": true, "schema": schema{"type": "string"}})
	}
	if route.Retry == capability.RetryIdempotencyKey {
		params = append(params, schema{"name": "Idempotency-Key", "in": "header", "schema": schema{"type": "string"}, "description": "Retain one key and the exact body when replaying a request."})
	}
	responses := schema{"default": schema{"description": "Canonical API failure.", "content": jsonContent(builder.value(reflect.TypeFor[apierr.Envelope]()))}}
	if known {
		op["summary"] = body.summary
		if body.request != nil {
			op["requestBody"] = schema{"required": true, "content": jsonContent(builder.value(body.request))}
		}
		if body.response != nil {
			responses["2XX"] = schema{"description": "Successful response.", "content": jsonContent(builder.value(body.response))}
		}
		if len(body.variants) > 0 {
			variants := []any{}
			for _, variant := range body.variants {
				variants = append(variants, builder.value(variant))
			}
			responses["2XX"] = schema{"description": "Response selected by the request operation.", "content": jsonContent(schema{"anyOf": variants})}
		}
		if body.response == nil && len(body.variants) == 0 {
			responses["204"] = schema{"description": "Completed without a response body."}
		}
		if body.selector != nil {
			params = append(params, schema{"name": "selector", "in": "query", "required": true, "content": jsonContent(builder.value(body.selector))})
		}
		params = append(params, body.parameters...)
	} else {
		op["x-sparkwing-wire"] = "undocumented"
		op["description"] = "Authorization is declared by the shared policy. A shared success-body contract is not documented for this operation."
	}
	if len(params) > 0 {
		op["parameters"] = params
	}
	op["responses"] = responses
	return op
}

func errorDefinitions() []schema {
	result := []schema{}
	for _, code := range apierr.Codes {
		result = append(result, schema{"code": code.Code, "http_status": code.HTTPStatus, "purpose": code.Purpose})
	}
	return result
}
