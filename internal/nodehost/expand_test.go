const testGenerator = "targets/generate/0"

type expansionWrites struct {
	storage.StateStoreOld
	nodes []store.Node
}

func (s *expansionWrites) CreateNode(_ context.Context, node store.Node) error {
	s.nodes = append(s.nodes, node)
	return nil
}

func (*expansionWrites) UpdateNodeDeps(context.Context, string, string, []string) error { return nil }
func (*expansionWrites) AppendEvent(context.Context, string, string, string, []byte) error {
	return nil
}

func (s *expansionWrites) ListNodes(context.Context, string) ([]*store.Node, error) {
	nodes := make([]*store.Node, 0, len(s.nodes))
	for i := range s.nodes {
		nodes = append(nodes, &s.nodes[i])
	}
	return nodes, nil
}

func TestSchedulerExpansionValidatesOriginalBytesBeforeWrites(t *testing.T) {
	valid := `{"id":"child","deps":["targets"],"groups":["targets/generate/0"],"steps":[{"id":"body"}]}`
	for name, raw := range map[string]string{
		"unknown":   strings.Replace(valid, `"id":"child"`, `"id":"child","ignored":true`, 1),
		"duplicate": strings.Replace(valid, `"id":"child"`, `"id":"discarded","id":"child"`, 1),
		"null":      strings.Replace(valid, `"deps":["targets"]`, `"deps":["targets"],"env":null`, 1),
		"cycle":     strings.Replace(valid, `["targets"]`, `["targets","summary"]`, 1),
	} {
		t.Run(name, func(t *testing.T) {
			doc := fanOutDoc()
			writes := &expansionWrites{}
			s := &scheduler{run: &Run{ID: testRunID, Doc: doc, State: writes, Logger: slog.New(slog.DiscardHandler), validation: nodeproto.ValidationContext{Placement: nodeproto.PlacementLocal, Secrets: noV2Secrets{}}}, nodes: slices.Clone(doc.Jobs), results: map[string]Result{}, started: map[string]bool{}}
			s.expand(t.Context(), "targets", Result{Outcome: sparkwing.Success, expansions: []expansion{{closure: testGenerator, raw: json.RawMessage("[" + raw + "]")}}})
			if len(writes.nodes) != 0 || !s.group(testGenerator).done || s.group(testGenerator).err == nil {
				t.Fatalf("invalid generated bytes escaped validation: writes=%d error=%v", len(writes.nodes), s.group(testGenerator).err)
			}
		})
	}
}

func TestSchedulerExpansionValidatesSourceBatchesTogether(t *testing.T) {
	first := `{"id":"one","deps":["targets","two"],"groups":["targets/generate/0"],"steps":[{"id":"body"}]}`
	second := `{"id":"two","deps":["targets"],"groups":["targets/generate/1"],"steps":[{"id":"body"}]}`
	for _, mode := range []string{"forward_dependency", "cycle", "recovery", "implicit_source"} {
		t.Run(mode, func(t *testing.T) {
			doc := fanOutDoc()
			doc.Jobs[0].Closures.Generate = append(doc.Jobs[0].Closures.Generate, "targets/generate/1")
			one, two := first, second
			switch mode {
			case "cycle":
				two = strings.Replace(two, `["targets"]`, `["targets","one"]`, 1)
			case "recovery":
				one = strings.Replace(one, `"deps":["targets","two"]`, `"on_failure_of":"two"`, 1)
			case "implicit_source":
				one = strings.Replace(one, `"deps":["targets","two"],`, ``, 1)
			}
			writes := &expansionWrites{}
			s := &scheduler{run: &Run{ID: testRunID, Doc: doc, State: writes, Logger: slog.New(slog.DiscardHandler), validation: nodeproto.ValidationContext{Placement: nodeproto.PlacementLocal, Secrets: noV2Secrets{}}}, nodes: slices.Clone(doc.Jobs), results: map[string]Result{}, started: map[string]bool{}}
			s.expand(t.Context(), "targets", Result{Outcome: sparkwing.Success, expansions: []expansion{
				{closure: testGenerator, raw: json.RawMessage("[" + one + "]")},
				{closure: "targets/generate/1", raw: json.RawMessage("[" + two + "]")},
			}})
			if mode == "cycle" {
				if len(writes.nodes) != 0 || s.group(testGenerator).err == nil || s.group("targets/generate/1").err == nil {
					t.Fatal("cyclic source batches produced rows")
				}
			} else if len(writes.nodes) != 2 || s.group(testGenerator).err != nil || s.group("targets/generate/1").err != nil {
				t.Fatalf("valid source batches were not accepted together: rows=%d errors=%v/%v", len(writes.nodes), s.group(testGenerator).err, s.group("targets/generate/1").err)
			}
		})
	}
}

func TestSchedulerExpansionFanOutBoundary(t *testing.T) {
	for _, count := range []int{256, 257} {
		t.Run(fmt.Sprint(count), func(t *testing.T) {
			jobs := make([]json.RawMessage, 0, count)
			for i := range count {
				jobs = append(jobs, json.RawMessage(fmt.Sprintf(`{"id":"child-%d","deps":["targets"],"groups":["targets/generate/0"],"steps":[{"id":"body"}]}`, i)))
			}
			raw, err := json.Marshal(jobs)
			if err != nil {
				t.Fatal(err)
			}
			doc := fanOutDoc()
			writes := &expansionWrites{}
			s := &scheduler{run: &Run{ID: testRunID, Doc: doc, State: writes, Logger: slog.New(slog.DiscardHandler), validation: nodeproto.ValidationContext{Placement: nodeproto.PlacementLocal, Secrets: noV2Secrets{}}}, nodes: slices.Clone(doc.Jobs), results: map[string]Result{}, started: map[string]bool{}}
			s.expand(t.Context(), "targets", Result{Outcome: sparkwing.Success, expansions: []expansion{{closure: testGenerator, raw: raw}}})
			if count == 256 && (len(writes.nodes) != count || s.group(testGenerator).err != nil) || count == 257 && (len(writes.nodes) != 0 || s.group(testGenerator).err == nil) {
				t.Fatalf("fan-out=%d rows=%d error=%v", count, len(writes.nodes), s.group(testGenerator).err)
			}
		})
	}
}

func FuzzGeneratorReplayPreservesEveryAcceptedDeclaration(f *testing.F) {
	f.Add("sibling", false, false, false)
	f.Add("changed", false, false, false)
	f.Add("sibling", true, false, false)
	f.Add("sibling", false, true, false)
	f.Add("sibling", false, false, true)
	f.Fuzz(func(t *testing.T, siblingID string, optional, add, partial bool) {
		doc := fanOutDoc()
		writes := &expansionWrites{}
		run := &Run{ID: testRunID, Doc: doc, State: writes, Logger: slog.New(slog.DiscardHandler), validation: nodeproto.ValidationContext{Placement: nodeproto.PlacementLocal, Secrets: noV2Secrets{}}}
		s := &scheduler{run: run, nodes: slices.Clone(doc.Jobs), results: map[string]Result{}, started: map[string]bool{}}
		jobs := []nodeproto.JobSpec{
			{ID: "leaf", Groups: []string{testGenerator}, Needs: []string{"targets"}, Steps: []nodeproto.StepSpec{{ID: "body"}}},
			{ID: "sibling", Groups: []string{testGenerator}, Needs: []string{"targets"}, Steps: []nodeproto.StepSpec{{ID: "body"}}},
		}
		accepted, err := json.Marshal(jobs)
		if err != nil {
			t.Fatal(err)
		}
		s.expand(t.Context(), "targets", Result{Outcome: sparkwing.Success, expansions: []expansion{{closure: testGenerator, raw: accepted}}})
		if len(writes.nodes) != 2 || s.group(testGenerator).err != nil {
			t.Fatal("accepted replay fixture was refused:", s.group(testGenerator).err)
		}
		if partial {
			writes.nodes = writes.nodes[:1]
		}
		stored := len(writes.nodes)
		jobs[1].ID, jobs[1].Optional = siblingID, optional
		if add {
			jobs = append(jobs, nodeproto.JobSpec{ID: "extra", Groups: []string{testGenerator}, Needs: []string{"targets"}, Steps: []nodeproto.StepSpec{{ID: "body"}}})
		}
		raw, err := json.Marshal(jobs)
		if err != nil {
			t.Fatal(err)
		}
		replayed, err := replayGeneratorJobs(t.Context(), &NodeRun{Run: run, Plan: jobs[0]}, testGenerator, raw)
		unchanged := siblingID == "sibling" && !optional && !add && !partial
		if unchanged != (err == nil) || !unchanged && replayed != nil || len(writes.nodes) != stored {
			t.Fatal("generator replay changed accepted membership or a sibling declaration")
		}
	})
}

func fanOutDoc() nodeproto.PlanDoc {
	return nodeproto.PlanDoc{Jobs: []nodeproto.JobSpec{
		{ID: "targets", Closures: nodeproto.ClosureSpec{Generate: []string{testGenerator}}, Steps: []nodeproto.StepSpec{{ID: "body"}}},
		{ID: "summary", Needs: deps("lint"), NeedsGenerated: []string{testGenerator}, Steps: []nodeproto.StepSpec{{ID: "body"}}},
		{ID: "lint", Steps: []nodeproto.StepSpec{{ID: "body"}}},
	}}
}

func generates(nodes ...nodeproto.JobSpec) Executor {
	return func(context.Context, *NodeRun) Result {
		return Result{Outcome: sparkwing.Success, expansions: []expansion{{closure: testGenerator, nodes: nodes}}}
	}
}

func TestExpansionFansOutAndHoldsItsWaiter(t *testing.T) {
	st := openStore(t)
	var children []nodeproto.JobSpec
	for i := range 5 {
		children = append(children, nodeproto.JobSpec{ID: fmt.Sprintf("test-%d", i), Needs: deps("targets"), Steps: []nodeproto.StepSpec{{ID: "body"}}})
	}
	fx := &fakeExec{bodies: map[string]Executor{"targets": generates(children...)}}

	res := hostDoc(t, t.Context(), st, fanOutDoc(), fx.run)

	if res.Status != "success" {
		t.Fatalf("status=%s err=%v, want success", res.Status, res.Err)
	}
	last := slices.Index(res.Order, "summary")
	for _, c := range children {
		wantRow(t, st, c.ID, sparkwing.Success, "")
		if i := slices.Index(res.Order, c.ID); i < 0 || i > last {
			t.Errorf("order %v: %s did not run before summary", res.Order, c.ID)
		}
		if got := fx.seen[c.ID].Generators; !slices.Equal(got, []string{testGenerator}) {
			t.Errorf("%s ran with generator %q, want %q", c.ID, got, testGenerator)
		}
	}
	if got := fx.seen["summary"].Generators; len(got) != 0 {
		t.Errorf("summary ran with generator %q, want none", got)
	}
	row := nodeRow(t, st, "summary")
	if want := []string{"lint", "test-0", "test-1", "test-2", "test-3", "test-4"}; !slices.Equal(row.Deps, want) {
		t.Errorf("summary row deps = %v, want %v", row.Deps, want)
	}
}

func TestExpansionFailureCancelsItsWaiter(t *testing.T) {
	child := nodeproto.JobSpec{ID: "test-a", Needs: deps("targets"), Steps: []nodeproto.StepSpec{{ID: "body"}}}
	cases := []struct {
		name   string
		source Executor
		errHas string
	}{
		{"GeneratorError", func(context.Context, *NodeRun) Result {
			return Result{Outcome: sparkwing.Success, expansions: []expansion{{closure: testGenerator, err: errors.New("generator panicked")}}}
		}, "expansion failed: generator panicked"},
		{"SourceFailed", func(context.Context, *NodeRun) Result {
			return Result{Outcome: sparkwing.Failed, Err: errors.New("broke"), expansions: []expansion{{closure: testGenerator, nodes: []nodeproto.JobSpec{child}}}}
		}, `expansion source "targets" did not succeed (outcome=failed)`},
		{"SourceSkippedTheGenerator", func(context.Context, *NodeRun) Result {
			return Result{Outcome: sparkwing.Skipped}
		}, "generator targets/generate/0 did not run"},
		{"DuplicateID", generates(child, nodeproto.JobSpec{ID: "lint", Needs: deps("targets"), Steps: []nodeproto.StepSpec{{ID: "body"}}}), "the plan holds node lint twice"},
		{"DuplicateWithinTheBatch", generates(child, child), "the plan holds node test-a twice"},
		{"NodeThatSkipsItsSource", generates(child, nodeproto.JobSpec{ID: "test-b", Steps: []nodeproto.StepSpec{{ID: "body"}}}), "does not need its source targets"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			st := openStore(t)
			fx := &fakeExec{bodies: map[string]Executor{"targets": tc.source}}
			res := hostDoc(t, t.Context(), st, fanOutDoc(), fx.run)
			if res.Status != "failed" {
				t.Errorf("status=%s err=%v, want failed", res.Status, res.Err)
			}
			wantRow(t, st, "summary", sparkwing.Cancelled, tc.errHas)
			if fx.ran("summary") || fx.ran("test-a") || fx.ran("test-b") {
				t.Errorf("ran %v, want neither summary nor a generated node", fx.calls)
			}
			if !fx.ran("lint") || len(fx.calls) != 2 {
				t.Errorf("ran %v, want targets and lint only", fx.calls)
			}
			if _, err := st.GetNode(t.Context(), testRunID, "test-a"); err == nil {
				t.Error("a refused generated node got a row")
			}
		})
	}
}

func TestExpansionDuringCancellationCancelsTheGeneratedNodes(t *testing.T) {
	st := openStore(t)
	ctx, cancel := context.WithCancel(t.Context())
	defer cancel()
	child := nodeproto.JobSpec{ID: "test-a", Needs: deps("targets"), Steps: []nodeproto.StepSpec{{ID: "body"}}}
	fx := &fakeExec{bodies: map[string]Executor{"targets": func(context.Context, *NodeRun) Result {
		cancel()
		return Result{Outcome: sparkwing.Success, expansions: []expansion{{closure: testGenerator, nodes: []nodeproto.JobSpec{child}}}}
	}}}
	doc := fanOutDoc()
	doc.Jobs[1].Needs = nil

	res := hostDoc(t, ctx, st, doc, fx.run)

	if res.Status != "failed" {
		t.Errorf("status=%s err=%v, want failed", res.Status, res.Err)
	}
	wantRow(t, st, "test-a", sparkwing.Cancelled, "ctx-cancelled")
	wantRow(t, st, "summary", sparkwing.Cancelled, "ctx-cancelled")
	if fx.ran("test-a") || fx.ran("summary") {
		t.Errorf("ran %v after the run was cancelled", fx.calls)
	}
}

func TestValidateNodesChecksGeneratedEdges(t *testing.T) {
	doc := fanOutDoc()
	doc.Jobs[1].NeedsGenerated = []string{"elsewhere/generate/0"}
	if err := validateNodes(doc.Jobs, nodeproto.ValidationContext{Placement: nodeproto.PlacementLocal, Secrets: noV2Secrets{}}); err == nil || !strings.Contains(err.Error(), "generator is absent or self-referential") {
		t.Errorf("unknown generator: err = %v", err)
	}
	doc = fanOutDoc()
	doc.Jobs[0].Needs = deps("summary")
	if err := validateNodes(doc.Jobs, nodeproto.ValidationContext{Placement: nodeproto.PlacementLocal, Secrets: noV2Secrets{}}); err == nil || !strings.Contains(err.Error(), "dependency cycle") {
		t.Errorf("a source that needs its own waiter: err = %v", err)
	}
}
